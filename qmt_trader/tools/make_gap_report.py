# -*- coding: utf-8 -*-
"""生成底部跳空扫描报告。"""
from __future__ import annotations
import os, sys, glob
from pathlib import Path
import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "output"


def W(writer, name, widths):
    ws = writer.sheets[name]
    from openpyxl.utils import get_column_letter
    for i, x in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = x


def main():
    xlsx = HERE / "底部跳空扫描_20261015.xlsx"
    G = pd.read_csv(OUT / "gap_final_20261015.csv") \
        if (OUT / "gap_final_20261015.csv").exists() else pd.DataFrame()
    E = pd.read_csv(OUT / "gap_bt_events.csv") \
        if (OUT / "gap_bt_events.csv").exists() else pd.DataFrame()

    with pd.ExcelWriter(xlsx, engine="openpyxl") as w:
        # 1 结论
        s1 = pd.DataFrame([
            ["扫描日期", "2026-10-15（最新完整交易日）"],
            ["说明", "今天是 2026-10-16（周五），当前盘中，日线收盘后才有"],
            ["", ""],
            ["★ 直接回答", ""],
            ["向上跳空标的", "9 只"],
            ["其中在底部的", "0 只"],
            ["", ""],
            ["【为什么是 0 只】", ""],
            ["", "今天所有跳空股的位置分位都在 47%~100%"],
            ["", "按定义，位置<20% 才算「底部」"],
            ["", "这 9 只都在中位以上，甚至是区间新高（100%）"],
            ["", ""],
            ["【最接近底部的一只】", ""],
            ["湖南发展 000722", "位置 47.3%，距130日高点 -21.7%"],
            ["", "但仍不算底部（位置>20%）"],
            ["", ""],
            ["【今天这 9 只的实际性质】", ""],
            ["", "6 只位置 = 100%（当日创 130 日新高）"],
            ["", "8 只涨停或接近涨停（涨跌 >= 9.98%）"],
            ["", "→ 这是「突破跳空」/「加速跳空」，不是「底部跳空」"],
            ["", ""],
            ["【回测数据：底部跳空 vs 突破跳空】", ""],
            ["位置<20% + 非涨停", "20日胜率 61.2%，平均 +6.65%  ← 底部跳空（有效）"],
            ["位置>50%", "20日平均 -0.73%，胜率 39.8%  ← 高位跳空（无效）"],
            ["当日涨停", "20日胜率 43.9%，平均 +1.00%  ← 追涨停（无效）"],
        ], columns=["项目", "内容"])
        s1.to_excel(w, sheet_name="1_结论", index=False)
        W(w, "1_结论", [26, 76])

        # 2 今日命中
        if len(G):
            G.to_excel(w, sheet_name="2_今日跳空标的", index=False)
            W(w, "2_今日跳空标的", [10, 8, 12, 12, 9, 9, 9, 9, 9, 9, 9, 9, 9, 10, 10, 10, 10, 10])

        # 3 分组
        if len(G):
            def grp(r):
                if r["位置%"] <= 20 and r["涨跌%"] < 9.5:
                    return "A组 底部+非涨停"
                if 20 < r["位置%"] <= 30 and r["涨跌%"] < 9.5:
                    return "B组 次优"
                if r["位置%"] <= 25 and r["涨跌%"] >= 9.5:
                    return "C组 底部+涨停"
                return "D组 非底部"
            G2 = G.copy()
            G2["分组"] = G2.apply(grp, axis=1)
            s3 = G2[["分组", "代码", "名称", "行业", "跳空%", "涨跌%",
                     "位置%", "距高%", "距MA60%"]].sort_values(
                ["分组", "位置%"])
            s3.to_excel(w, sheet_name="3_分组", index=False)
            W(w, "3_分组", [18, 10, 11, 11, 9, 9, 9, 9, 10])

            # 分组汇总
            s3b = G2.groupby("分组").agg(
                数量=("代码", "size"),
                平均跳空=("跳空%", "mean"),
                平均位置=("位置%", "mean"),
                平均距高=("距高%", "mean")).round(2).reset_index()
            s3b.to_excel(w, sheet_name="4_分组汇总", index=False)
            W(w, "4_分组汇总", [18, 8, 11, 11, 11])

        # 5 回测依据
        s5 = pd.DataFrame([
            ["位置<10% + 非涨停", 1674, "+4.03%", "+7.83%", "+10.18%",
             "63.3%", "62.7%", "59.2%", "-7.70%"],
            ["位置<15% + 非涨停", 4352, "+3.68%", "+7.04%", "+8.66%",
             "61.8%", "62.2%", "56.7%", "-7.36%"],
            ["位置<20% + 非涨停", 7188, "+3.49%", "+6.65%", "+8.21%",
             "60.8%", "61.2%", "56.9%", "-7.25%"],
            ["位置<20% + 涨停", 1308, "+6.46%", "+10.16%", "+7.51%",
             "61.4%", "64.5%", "52.4%", "-12.38%"],
            ["位置 20-30%", 7298, "+2.02%", "+2.02%", "+2.67%",
             "—", "49.8%", "—", "—"],
            ["位置 >50%", 7299, "—", "-0.73%", "+0.54%",
             "—", "39.8%", "—", "—"],
            ["当日涨停（不限位置）", 9558, "+0.34%", "+1.00%", "-1.17%",
             "44.1%", "43.9%", "36.9%", "-14.66%"],
            ["当日非涨停（不限位置）", 26935, "+1.66%", "+3.36%", "+5.49%",
             "54.1%", "53.6%", "51.5%", "-8.77%"],
            ["全市场随机基准", 243813, "+0.44%", "+1.38%", "+3.25%",
             "49.2%", "49.2%", "47.5%", "-9.27%"],
        ], columns=["群体", "样本", "5日", "20日", "60日",
                    "5日胜率", "20日胜率", "60日胜率", "20日内浮亏"])
        s5.to_excel(w, sheet_name="5_回测依据", index=False)
        W(w, "5_回测依据", [22, 10, 9, 9, 9, 10, 10, 10, 12])

        # 6 定义与参数
        s6 = pd.DataFrame([
            ["跳空定义", "今日最低价 > 昨日最高价（向上跳空缺口未回补）"],
            ["最小跳空幅度", "0.2%"],
            ["位置定义", "(今收 - 130日最低) / (130日最高 - 130日最低)"],
            ["底部定义", "位置分位 <= 20%  或  距130日高点 <= -15%"],
            ["", ""],
            ["数据来源", "Tushare daily（按日全市场）+ 本地前复权K线"],
            ["覆盖", "4977 只（排除 ST/退/北交所/上市不足200天）"],
            ["", ""],
            ["★ 关键区分", ""],
            ["底部跳空", "股价在低位出现向上跳空 → 有效（20日胜率61%）"],
            ["突破跳空", "股价在高位或创新高时跳空 → 无效（胜率40%）"],
            ["涨停跳空", "跳空同时涨停 → 弹性大但浮亏深（-12.4%）"],
            ["", ""],
            ["今日情况", "9 只跳空，全部属于「突破跳空」或「涨停跳空」"],
            ["", "没有一只是「底部跳空」"],
        ], columns=["项目", "说明"])
        s6.to_excel(w, sheet_name="6_定义与说明", index=False)
        W(w, "6_定义与说明", [16, 72])

    print(f"已生成: {xlsx}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
