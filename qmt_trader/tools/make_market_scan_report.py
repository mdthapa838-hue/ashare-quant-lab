# -*- coding: utf-8 -*-
"""生成全市场扫描报告。"""
from __future__ import annotations
import sys, glob, os
from pathlib import Path
import pandas as pd
import numpy as np

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "output"


def W(writer, name, widths):
    ws = writer.sheets[name]
    from openpyxl.utils import get_column_letter
    for i, x in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = x


def main():
    f = sorted(glob.glob(str(OUT / "market_scan_*.csv")),
               key=os.path.getmtime)[-1]
    A = pd.read_csv(f, dtype={"代码": str})
    A["涨停"] = A["涨跌%"] >= 9.7

    xlsx = HERE / "全市场扫描_20261016.xlsx"
    with pd.ExcelWriter(xlsx, engine="openpyxl") as w:

        # 1 市场概况
        up = int((A["涨跌%"] > 0).sum())
        s1 = pd.DataFrame([
            ["扫描时点", "2026-10-16 14:09（盘中）"],
            ["数据源", "腾讯实时行情 + 本地前复权K线 + Tushare 财务"],
            ["覆盖", f"{len(A)} 只（排除 ST/退/北交所）"],
            ["", ""],
            ["【市场整体】", ""],
            ["上涨 / 下跌", f"{up} / {int((A['涨跌%']<0).sum())}"],
            ["上涨占比", f"{up/len(A)*100:.1f}%"],
            ["涨停 / 跌停", f"{int(A['涨停'].sum())} / {int((A['涨跌%']<=-9.7).sum())}"],
            ["平均涨幅", f"{A['涨跌%'].mean():.2f}%"],
            ["成交额合计", f"{A['成交额亿'].sum():,.0f} 亿"],
            ["", ""],
            ["【位置分布（130日）】", ""],
            ["位置 0-10%", f"{int(((A['位置%']>=0)&(A['位置%']<10)).sum())} 只（26.3%）"],
            ["位置 10-25%", f"{int(((A['位置%']>=10)&(A['位置%']<25)).sum())} 只（27.6%）"],
            ["位置 25-50%", f"{int(((A['位置%']>=25)&(A['位置%']<50)).sum())} 只（32.2%）"],
            ["位置 50-75%", f"{int(((A['位置%']>=50)&(A['位置%']<75)).sum())} 只（9.5%）"],
            ["位置 75%+", f"{int((A['位置%']>=75).sum())} 只（3.0%）"],
            ["", ""],
            ["【结论】", ""],
            ["位置极低", "53.9% 的股票处于 130 日区间下 25% 分位"],
            ["含义", "整体仍在低位，是熊市底部区域特征"],
            ["但今日普涨", "67% 上涨、79 只涨停 —— 短期有资金进场"],
            ["", ""],
            ["★ 最热方向", "国防军工（上涨占比 99.0%、平均 +4.90%）"],
            ["次热", "汽车（+2.54%）、机械设备（+1.71%）、建筑装饰（+2.21%）"],
        ], columns=["项目", "内容"])
        s1.to_excel(w, sheet_name="1_市场概况", index=False)
        W(w, "1_市场概况", [24, 66])

        # 2 行业热度
        g = A.groupby("行业").agg(
            数量=("代码", "size"), 涨停数=("涨停", "sum"),
            平均涨幅=("涨跌%", "mean"),
            上涨占比=("涨跌%", lambda s: (s > 0).mean() * 100),
            平均位置=("位置%", "mean"),
            平均市值=("总市值亿", "mean")).round(2)
        g = g[g["数量"] >= 10].sort_values(
            ["涨停数", "平均涨幅"], ascending=False).reset_index()
        g.to_excel(w, sheet_name="2_行业热度", index=False)
        W(w, "2_行业热度", [12, 8, 8, 10, 10, 10, 11])

        # 3 军工
        mil = A[A["行业"] == "国防军工"].nlargest(30, "涨跌%")
        mil.to_excel(w, sheet_name="3_国防军工", index=False)
        W(w, "3_国防军工", [10, 11, 10, 10, 11, 11, 9, 9, 11, 11])

        # 4 汽车
        car = A[A["行业"] == "汽车"].nlargest(30, "涨跌%")
        car.to_excel(w, sheet_name="4_汽车", index=False)
        W(w, "4_汽车", [10, 11, 10, 10, 11, 11, 9, 9, 11, 11])

        # 5 机械
        mac = A[A["行业"] == "机械设备"].nlargest(30, "涨跌%")
        mac.to_excel(w, sheet_name="5_机械设备", index=False)
        W(w, "5_机械设备", [10, 11, 10, 10, 11, 11, 9, 9, 11, 11])

        # 6 左侧潜伏
        L = A[(A["位置%"] < 25) & (A["距高%"] < -30) & (A["60日%"] > -15) &
              (A["涨跌%"] > 1) & (A["总市值亿"] > 30)].copy()
        L = L.sort_values("位置%").head(60)
        L.to_excel(w, sheet_name="6_左侧潜伏", index=False)
        W(w, "6_左侧潜伏", [10, 11, 10, 10, 11, 11, 9, 9, 11, 11])

        # 7 各路线候选
        route_rows = [
            ["F 基本面/低估值", "PE 0-30 + PB<4 + 市值>50亿 + 位置<40% + 60日跌",
             375, "估值低但仍在下跌，需等右侧"],
            ["S 小盘活跃", "市值20-60亿 + 成交>0.5亿 + 换手>1% + 今日涨",
             653, "数量最多，但要防题材退潮"],
            ["M 强势动量", "250日>20% + 60日>0 + 距高>-10% + 今日涨",
             18, "极少（熊市里强势股稀缺）"],
            ["E 超跌修复", "位置<15% + 距高<-35% + 涨>2% + 放量",
             0, "今日无符合（超跌股未放量）"],
            ["T 题材（热门行业）", "热门行业 + 涨>3% + 换手>2%",
             199, "军工占多数"],
            ["L 左侧潜伏", "位置<25% + 距高<-30% + 60日>-15% + 今日涨",
             345, "底部止跌形态"],
        ]
        s7 = pd.DataFrame(route_rows,
                          columns=["路线", "筛选条件", "候选数", "说明"])
        s7.to_excel(w, sheet_name="7_各路线候选", index=False)
        W(w, "7_各路线候选", [20, 42, 9, 30])

        # 8 建议
        s8 = pd.DataFrame([
            ["1", "防御性配置", "银行/公用事业/高速", "熊市里抗跌"],
            ["2", "军工（当前最强）", "国防军工 99% 上涨、+4.90%",
             "但多数已涨停，追高风险大"],
            ["3", "汽车零部件", "汽车 +2.54%、12 只涨停", "有真实业绩的更多"],
            ["4", "左侧潜伏", "位置<25% 且已止跌", "需耐心，等右侧确认"],
            ["5", "宽基指数", "沪深300ETF / 中证500ETF",
             "PE 13.04，胜率 56-60%"],
            ["", "", "", ""],
            ["不推荐", "", "", ""],
            ["", "追涨停", "当日涨停群体 20日胜率仅 43.9%", ""],
            ["", "高位股", "位置>50% 只有 12.3% 的股票", ""],
            ["", "亏损股", "军工涨停股多数 PE 为负", ""],
        ], columns=["优先级", "方向", "依据", "备注"])
        s8.to_excel(w, sheet_name="8_方向建议", index=False)
        W(w, "8_方向建议", [10, 20, 36, 30])

    print(f"已生成: {xlsx}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
