# -*- coding: utf-8 -*-
"""生成「缩量筑底」形态历史统计报告。"""
from __future__ import annotations
import sys
from pathlib import Path
import pandas as pd

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "output"


def W(writer, name, widths):
    ws = writer.sheets[name]
    from openpyxl.utils import get_column_letter
    for i, x in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = x


def main():
    E = pd.read_csv(OUT / "washout_base_events.csv")
    E["date"] = pd.to_datetime(E["date"])
    B = pd.read_csv(OUT / "washout_base_baseline.csv")
    per_day = E.groupby("date").size()

    xlsx = HERE / "缩量筑底形态统计_20261016.xlsx"
    with pd.ExcelWriter(xlsx, engine="openpyxl") as w:

        # 1 直接回答
        s1 = pd.DataFrame([
            ["问题", "协创数据这种「缩量筑底」形态，历史上多吗？"],
            ["", ""],
            ["★ 直接回答", ""],
            ["答案", "【不算罕见】—— 平均每个交易日有 12 只符合"],
            ["", ""],
            ["【频率数据】", ""],
            ["总匹配事件", f"{len(E):,} 个（14.7 年）"],
            ["涉及股票", f"{E['code'].nunique():,} 只"],
            ["平均每日", f"{per_day.mean():.0f} 只"],
            ["中位每日", f"{per_day.median():.0f} 只"],
            ["最多一天", f"{per_day.max():,} 只（2024-06-06）"],
            ["", ""],
            ["每日数量分布", ""],
            ["1~5 只", "1,023 天（49.2%）"],
            ["5~20 只", "718 天（34.6%）"],
            ["20~50 只", "242 天（11.6%）"],
            ["50~100 只", "72 天（3.5%）"],
            ["100+ 只", "23 天（1.1%）"],
            ["", ""],
            ["★ 形态之后怎么走", ""],
            ["20日", "平均 +2.95%  胜率 54.9%"],
            ["60日", "平均 +3.84%  胜率 51.3%"],
            ["120日", "平均 +10.80%  胜率 56.2%"],
            ["250日", "平均 +19.96%  胜率 55.8%"],
            ["", ""],
            ["★ 相对随机基准的超额", ""],
            ["20日", "+1.49pct（胜率 +5.4pct）"],
            ["60日", "+0.17pct（胜率 +3.0pct）"],
            ["120日", "+3.86pct（胜率 +6.4pct）"],
            ["250日", "+5.09pct（胜率 +5.0pct）"],
            ["", ""],
            ["★ 结论", ""],
            ["", "形态有效，但优势有限（超额 0.2~5pct）"],
            ["", "不是「抄底神器」，更像「略优于平均」"],
            ["", "且 60 日内平均浮亏 -15.29%（必须能扛）"],
        ], columns=["项目", "内容"])
        s1.to_excel(w, sheet_name="1_直接回答", index=False)
        W(w, "1_直接回答", [20, 62])

        # 2 形态定义
        s2 = pd.DataFrame([
            ["a) 距250日高点", "<= -30%", "跌得够多", "协创: -42.19% ✅"],
            ["b) 量能比 v20/v60", "<= 0.75", "显著缩量", "协创: 0.619 ✅"],
            ["c) 波动比 v20d/v60d", "<= 0.80", "波动收缩", "协创: 0.66 ✅"],
            ["d) 位置（20日区间）", "<= 30%", "接近短期底部", "协创: 14.7% ✅"],
            ["e) 距MA20", "<= -8%", "均线破位", "协创: -13.3% ✅"],
            ["", "", "", ""],
            ["严格版（更接近协创）", "", "", ""],
            ["a) 距250日高点", "<= -35%", "", "协创: -42.19% ✅"],
            ["b) 量能比", "<= 0.70", "", "协创: 0.619 ✅"],
            ["c) 波动比", "<= 0.75", "", "协创: 0.66 ✅"],
            ["d) 位置", "<= 20%", "", "协创: 14.7% ✅"],
            ["e) 距MA20", "<= -10%", "", "协创: -13.3% ✅"],
        ], columns=["条件", "阈值", "含义", "协创数据是否符合"])
        s2.to_excel(w, sheet_name="2_形态定义", index=False)
        W(w, "2_形态定义", [22, 12, 18, 26])

        # 3 前瞻收益
        rows = []
        for hz in (20, 60, 120, 250):
            v = E[f"f{hz}"].dropna()
            vb = B[f"f{hz}"].dropna()
            rows.append({
                "持有期": f"{hz}日", "样本": len(v),
                "平均%": round(v.mean(), 2), "中位%": round(v.median(), 2),
                "胜率%": round((v > 0).mean() * 100, 1),
                "最好%": round(v.max(), 1), "最差%": round(v.min(), 1),
                "25分位%": round(v.quantile(.25), 2),
                "75分位%": round(v.quantile(.75), 2),
                "随机基准平均%": round(vb.mean(), 2),
                "随机基准胜率%": round((vb > 0).mean() * 100, 1),
                "超额%": round(v.mean() - vb.mean(), 2),
            })
        pd.DataFrame(rows).to_excel(w, sheet_name="3_前瞻收益", index=False)
        W(w, "3_前瞻收益", [9, 9, 9, 9, 8, 9, 9, 10, 10, 13, 14, 9])

        # 4 分层检验
        E2 = E.dropna(subset=["f60"]).copy()
        lay_rows = []

        def layer(col, label, q=4):
            try:
                E2["_q"] = pd.qcut(E2[col], q, labels=False, duplicates="drop")
            except Exception:
                return
            for g in sorted(E2["_q"].dropna().unique()):
                sub = E2[E2["_q"] == g]
                lo, hi = sub[col].min(), sub[col].max()
                v60 = sub["f60"].dropna()
                v250 = sub["f250"].dropna()
                lay_rows.append({
                    "分层变量": label,
                    "档": f"Q{int(g)+1}",
                    "范围": f"{lo:.2f}~{hi:.2f}",
                    "样本": len(sub),
                    "60日平均%": round(v60.mean(), 2),
                    "60日胜率%": round((v60 > 0).mean() * 100, 1),
                    "250日平均%": round(v250.mean(), 2) if len(v250) else None,
                    "250日胜率%": round((v250 > 0).mean() * 100, 1) if len(v250) else None,
                })
            E2.drop(columns=["_q"], inplace=True, errors="ignore")

        layer("dd250", "回撤深度")
        layer("vratio", "量能比")
        layer("vbratio", "波动比")
        layer("pos", "位置分位")
        layer("dvu", "下跌/上涨量能比")
        pd.DataFrame(lay_rows).to_excel(w, sheet_name="4_分层检验", index=False)
        W(w, "4_分层检验", [12, 8, 18, 8, 11, 11, 12, 12])

        # 5 分年度
        E2["yr"] = E2["date"].dt.year
        yr_rows = []
        for yr, g in E2.groupby("yr"):
            if len(g) < 30:
                continue
            v60 = g["f60"].dropna()
            v250 = g["f250"].dropna()
            yr_rows.append({
                "年份": yr, "事件数": len(g),
                "60日平均%": round(v60.mean(), 2),
                "60日胜率%": round((v60 > 0).mean() * 100, 1),
                "250日平均%": round(v250.mean(), 2) if len(v250) else None,
                "250日胜率%": round((v250 > 0).mean() * 100, 1) if len(v250) else None,
            })
        pd.DataFrame(yr_rows).to_excel(w, sheet_name="5_分年度", index=False)
        W(w, "5_分年度", [8, 10, 12, 12, 13, 13])

        # 6 关键发现
        s6 = pd.DataFrame([
            ["发现1", "「跌得越深，反弹越强」",
             "dd250 <-52% 档：60日胜率 57.0%，250日 +22.22%",
             "协创 -42.19% 在 Q3 档（47.6% 胜率）"],
            ["发现2", "「缩量越极端越好」",
             "vratio <0.50 档：60日胜率 53.4%，250日胜率 59.6%",
             "协创 0.619 在 Q3 档"],
            ["发现3", "★「波动收缩太极端反而不好」",
             "vbratio <0.59 档：60日胜率仅 47.4%（最差）",
             "协创 0.66 在 Q2~Q3 之间"],
            ["发现4", "「位置越极端越好」",
             "pos <2.21% 档：250日胜率 57.5%",
             "协创 14.7% 处于最差档（Q4: 56.6%）"],
            ["发现5", "★「下跌量能小于上涨量能不一定好」",
             "dvu <0.78 档：60日胜率 49.4%（最差）",
             "协创 0.87 在 Q2 档"],
            ["发现6", "★「分年度差异极大」",
             "2014年 250日胜率 98.1%；2017年仅 5.9%",
             "大盘环境决定成败"],
            ["发现7", "★「60日是最大的煎熬期」",
             "60日胜率仅 51.3%，平均浮亏 -15.29%",
             "120日升到 56.2%，250日 55.8%"],
        ], columns=["序号", "发现", "数据", "协创数据对照"])
        s6.to_excel(w, sheet_name="6_关键发现", index=False)
        W(w, "6_关键发现", [8, 26, 40, 30])

        # 7 对协创数据的应用
        s7 = pd.DataFrame([
            ["① 距250日高点", "-42.19%", "Q3档(-43.83~-37.10)", "47.6%", "250日 53.5%"],
            ["② 量能比", "0.619", "Q3档(0.59~0.67)", "50.4%", "250日 54.3%"],
            ["③ 波动比", "0.66", "Q2~Q3档(0.59~0.74)", "50.6~52.9%", "250日 55.6~55.8%"],
            ["④ 位置分位", "14.7%", "Q4档(10.60~29.95)", "52.1%", "250日 56.6%"],
            ["⑤ 下跌/上涨量能", "0.87", "Q2档(0.78~0.88)", "50.0%", "250日 55.0%"],
            ["", "", "", "", ""],
            ["综合对照", "", "各项均在 Q2~Q4 档", "约 50~53%", "约 54~57%"],
            ["", "", "", "", ""],
            ["★ 判定", "", "", "", ""],
            ["", "协创数据各项指标处于「中等偏弱」档", "", "", ""],
            ["", "不是最优形态（最优需要 dd250<-52% 或 pos<2%）", "", "", ""],
            ["", "预期 60日胜率约 50~52%，250日约 55%", "", "", ""],
            ["", "含义：与抛硬币接近，需要其他因素配合", "", "", ""],
        ], columns=["条件", "协创值", "所处档位", "60日胜率", "250日胜率"])
        s7.to_excel(w, sheet_name="7_对协创的应用", index=False)
        W(w, "7_对协创的应用", [16, 12, 22, 20, 20])

        # 8 结论与建议
        s8 = pd.DataFrame([
            ["1", "形态不罕见", "平均每交易日 12 只符合",
             "所以不能仅因「形态符合」就买入"],
            ["2", "有效但优势有限", "250日超额 +5.09pct",
             "比随机好，但不是「必胜」"],
            ["3", "60日是煎熬期", "胜率仅 51.3%，平均浮亏 -15.29%",
             "做好 6 个月不赚钱的准备"],
            ["4", "分年度差异极大", "2014年 250日胜率 98.1%，2017年仅 5.9%",
             "大盘环境决定成败"],
            ["5", "协创数据处于中等档", "各项指标 Q2~Q4",
             "不是最优形态"],
            ["6", "需要配合其他确认", "业绩/量能/均线",
             "不能只看形态"],
            ["", "", "", ""],
            ["对协创数据", "", "", ""],
            ["观察点1", "能否站回 MA20（247.12）", "", "右侧信号"],
            ["观察点2", "三季报是否确认高增长", "10月下旬", "基本面验证"],
            ["观察点3", "成交额是否放大", "每日", "资金回流信号"],
            ["失效条件", "跌破前低 203", "", "形态破坏"],
        ], columns=["#", "要点", "数据", "含义"])
        s8.to_excel(w, sheet_name="8_结论建议", index=False)
        W(w, "8_结论建议", [4, 22, 30, 34])

    print(f"已生成: {xlsx}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
