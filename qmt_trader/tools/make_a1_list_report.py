# -*- coding: utf-8 -*-
"""生成 A1 历史清单 + 可成交性报告。"""
from __future__ import annotations
import sys
from pathlib import Path
import pandas as pd

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "output"


def W(writer, name, widths):
    ws = writer.sheets[name]
    from openpyxl.utils import get_column_letter
    for i, x in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = x


def main():
    D = pd.read_csv(OUT / "a1_with_names.csv", dtype={"code": str}) \
        if (OUT / "a1_with_names.csv").exists() else pd.DataFrame()
    F = pd.read_csv(OUT / "a1_fillability.csv", dtype={"code": str}) \
        if (OUT / "a1_fillability.csv").exists() else pd.DataFrame()
    if len(F):
        F["date"] = pd.to_datetime(F["date"])
        F["名称"] = F["code"].map(
            dict(zip(D["code"], D["名称"])) if len(D) else {})

    xlsx = HERE / "A1历史清单与买入方法_20261016.xlsx"
    with pd.ExcelWriter(xlsx, engine="openpyxl") as w:

        # 1 直接回答
        s1 = pd.DataFrame([
            ["问题", "历史上有哪些 A1 股票？后面怎么买才能买到？"],
            ["", ""],
            ["★ 回答1：历史 A1 清单", ""],
            ["总数", "440 个信号，涉及 402 只股票"],
            ["时间", "2025-03 ~ 2026-10"],
            ["频率", "平均每日 4.23 只，59.1% 交易日有信号"],
            ["完整清单", "见「2_历史清单」工作表"],
            ["", ""],
            ["★ 回答2：能买到吗？", ""],
            ["**可买到**", "**428 / 440 = 97.3%**"],
            ["极难买到", "5 只（1.1%）— T+1 开盘涨停"],
            ["完全买不到", "7 只（1.6%）— T+1 一字板"],
            ["", ""],
            ["★ 可买到那批的表现（T+1 开盘买）", ""],
            ["20日", "**+6.71%  胜率 70.7%**"],
            ["60日", "**+9.87%  胜率 60.1%**"],
            ["→ 结论", "**可买到的部分仍显著为正，策略实际可行**"],
            ["", ""],
            ["★ 怎么买（核心技巧）", ""],
            ["方法", "集合竞价挂涨停价（09:20-09:25）"],
            ["原理", "A股集合竞价按「最大成交量价格」成交"],
            ["", "挂涨停价 → 实际成交价 = 开盘价"],
            ["效果", "只要开盘不是涨停，就能以开盘价买到"],
            ["", ""],
            ["★ 可买到比例（按跳空）", ""],
            ["跳空 2~3%", "98.6% 可买到"],
            ["跳空 3~5%", "99.3% 可买到"],
            ["跳空 5~8%", "98.9% 可买到"],
            ["跳空 8%+", "92.6% 可买到"],
            ["→ 建议", "优先跳空 3~5%（可成交率最高 + 收益好）"],
        ], columns=["项目", "内容"])
        s1.to_excel(w, sheet_name="1_直接回答", index=False)
        W(w, "1_直接回答", [26, 62])

        # 2 完整清单
        if len(D):
            D.to_excel(w, sheet_name="2_历史清单", index=False)
            W(w, "2_历史清单", [12, 9, 12, 10, 9, 8, 8, 8, 9, 8, 9, 10,
                                22, 9, 9, 9, 9, 9, 9])

        # 3 成功案例
        if len(D):
            D2 = D.copy()
            D2["C_f20"] = pd.to_numeric(D2["C_f20"], errors="coerce")
            win = D2[D2["C_f20"] > 20].sort_values("C_f20", ascending=False)
            if len(win):
                win[["date", "code", "名称", "行业", "g", "gap",
                     "C_f20", "C_f60"]].to_excel(
                    w, sheet_name="3_成功案例", index=False)
                W(w, "3_成功案例", [12, 9, 12, 12, 10, 9, 10, 10])
            # 亏损案例
            los = D2[D2["C_f20"] < -10].sort_values("C_f20")
            if len(los):
                los[["date", "code", "名称", "行业", "g", "gap",
                     "C_f20", "C_f60"]].to_excel(
                    w, sheet_name="4_亏损案例", index=False)
                W(w, "4_亏损案例", [12, 9, 12, 12, 10, 9, 10, 10])

        # 5 可成交性统计
        s5 = pd.DataFrame([
            ["✅ 可以买到（T+1开盘可成交）", 428, "97.3%",
             "+6.71%", "70.7%", "+9.87%", "60.1%"],
            ["⚠ 极难（T+1开盘涨停）", 5, "1.1%",
             "−8.17%", "20.0%", "−9.72%", "20.0%"],
            ["❌ 完全买不到（T+1一字板）", 7, "1.6%",
             "+15.64%", "42.9%", "+4.83%", "50.0%"],
        ], columns=["类别", "数量", "占比", "20日%", "20日胜率",
                    "60日%", "60日胜率"])
        s5.to_excel(w, sheet_name="5_可成交性", index=False)
        W(w, "5_可成交性", [28, 8, 9, 10, 11, 10, 11])

        # 6 按板块
        if len(F):
            F["板块"] = F["code"].apply(
                lambda c: "科创板(20%)" if c.startswith("68")
                else ("创业板(20%)" if c.startswith("30")
                      else "主板(10%)"))
            rows = []
            for b, g in F.groupby("板块"):
                if len(g) < 5:
                    continue
                v = pd.to_numeric(g["C_f20"], errors="coerce").dropna()
                ok = int(g["可成交性"].str.startswith("✅").sum())
                rows.append({
                    "板块": b, "样本": len(g),
                    "T+1开盘涨停": int(g["T1开盘涨停"].sum()),
                    "占比%": round(g["T1开盘涨停"].mean() * 100, 1),
                    "T+1一字": int(g["T1一字"].sum()),
                    "可买到": ok, "可买率%": round(ok / len(g) * 100, 1),
                    "20日%": round(v.mean(), 2) if len(v) else None,
                })
            if rows:
                pd.DataFrame(rows).to_excel(w, sheet_name="6_按板块",
                                             index=False)
                W(w, "6_按板块", [16, 8, 12, 9, 10, 9, 10, 9])

        # 7 按跳空
        s7 = pd.DataFrame([
            ["2~3%", 72, 1, "1.4%", 71, "98.6%", "+8.25%", "70.4%"],
            ["3~5%", 152, 1, "0.7%", 151, "99.3%", "+5.85%", "73.3%"],
            ["5~8%", 94, 1, "1.1%", 93, "98.9%", "+8.70%", "75.3%"],
            ["8%+", 122, 9, "7.4%", 113, "92.6%", "+5.24%", "63.4%"],
        ], columns=["跳空档", "样本", "买不到", "占比", "可买到",
                    "可买率", "可买到20日%", "可买到胜率"])
        s7.to_excel(w, sheet_name="7_按跳空", index=False)
        W(w, "7_按跳空", [10, 8, 9, 9, 9, 9, 12, 12])

        # 8 买入方法
        s8 = pd.DataFrame([
            ["【方法1】集合竞价挂涨停价", "", "", ""],
            ["原理", "A股集合竞价（09:15-09:25）以「最大成交量价格」成交",
             "", "挂涨停价 → 成交价 = 开盘价"],
            ["", "只要开盘不是涨停，就能以开盘价买到", "", ""],
            ["操作", "09:15-09:20  可挂可撤 → 观察竞价走势",
             "", ""],
            ["", "09:20-09:25  不可撤单 → 确认后挂涨停价",
             "", ""],
            ["", "09:25        成交价 = 开盘价", "", ""],
            ["优点", "不会因挂低价而错过", "", ""],
            ["风险", "若开盘就涨停，单子可能不成交（1.1% 概率）", "", ""],
            ["", "", "", ""],
            ["【方法2】分两笔", "", "", ""],
            ["", "09:25 竞价挂一半（涨停价）", "", "降低滑点"],
            ["", "09:30-09:35 观察，回踩则买另一半", "", ""],
            ["", "", "", ""],
            ["【方法3】避开易涨停的", "", "", ""],
            ["", "优先跳空 3~5%（可买率 99.3%）", "", ""],
            ["", "避开跳空 8%+（可买率 92.6%）", "", ""],
            ["", "", "", ""],
            ["【方法4】接受买不到", "", "", ""],
            ["", "历史 2.7% 买不到 —— 直接放弃", "",
             "不要追高、不要盘中乱买"],
        ], columns=["项目", "内容", "", "备注"])
        s8.to_excel(w, sheet_name="8_买入方法", index=False)
        W(w, "8_买入方法", [24, 46, 4, 30])

        # 9 完整执行流程
        s9 = pd.DataFrame([
            ["T日 15:00", "收盘", "记录：最低价 vs 前收、收盘 vs 前收",
             "判定是否「回补」"],
            ["T日 17-21时", "跑监控", "GUI → 找「A1 优选」（绿色）",
             "通常 1-5 只"],
            ["T日 21:00", "确认名单", "检查跳空%、回补、p60/p120",
             "硬门槛"],
            ["", "", "", ""],
            ["T+1 09:15", "看竞价", "若竞价已涨停 → 放弃", ""],
            ["T+1 09:20", "挂单", "★ 挂涨停价买入（集合竞价）", ""],
            ["T+1 09:25", "成交", "成交价 = 开盘价", ""],
            ["T+1 09:30", "观察", "若回踩 → 可补第二笔", ""],
            ["", "", "", ""],
            ["持有 20-60 日", "到期卖出", "PEAD 有效期",
             "不做长期持有"],
            ["止损", "−15%", "无条件卖出", "或跌破 T日最低"],
        ], columns=["时间", "动作", "内容", "备注"])
        s9.to_excel(w, sheet_name="9_执行流程", index=False)
        W(w, "9_执行流程", [16, 12, 40, 22])

        # 10 局限
        s10 = pd.DataFrame([
            ["1", "样本 440，涉及 402 只", "不算多", "需更多验证"],
            ["2", "样本期 1.7 年", "2025-03~2026-10", "含 2026 熊市"],
            ["3", "未含交易成本", "0.25%/来回", "需扣减"],
            ["4", "「可买到」用开盘价模拟", "", "实际可能有滑点"],
            ["5", "一字板仅 7 例", "统计意义有限", "但至少知道存在"],
            ["6", "集合竞价挂涨停价有风险",
             "若开盘就是涨停，可能成交在涨停价（贵）", "需注意"],
        ], columns=["#", "局限", "说明", "影响"])
        s10.to_excel(w, sheet_name="10_局限", index=False)
        W(w, "10_局限", [4, 26, 34, 22])

    print(f"已生成: {xlsx}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
